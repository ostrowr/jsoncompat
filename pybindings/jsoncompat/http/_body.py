"""Buffered HTTP media codecs. Model validation always precedes wire encoding."""

from __future__ import annotations

import base64
import re
import secrets
from email.message import Message
from urllib.parse import unquote

from jsoncompat import JsonValue, deserialize_json_value, serialize_json_value

from jsoncompat.codegen.serialization import (
    SerializationFormat,
    deserialize_value,
    serialize_value,
)

from ._metadata import Body, BodyCodec, FormField, Query
from ._parameters import encode_parameter, scalar


def media_type(value: str) -> tuple[str, dict[str, str]]:
    """Parse a Content-Type without confusing quoted semicolons with separators."""
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("invalid Content-Type")
    message = Message()
    message["content-type"] = value
    parts = message.get_params(header="content-type", unquote=True)
    if parts is None or not parts or not isinstance(parts[0][0], str):
        raise ValueError("invalid Content-Type")
    name = parts[0][0].lower()
    if not re.fullmatch(r"[!#$%&'*+.^_`|~0-9a-z-]+/[!#$%&'*+.^_`|~0-9a-z-]+", name):
        raise ValueError("invalid Content-Type")
    parameters: dict[str, str] = {}
    for key, item in parts[1:]:
        if not isinstance(item, str) or key.lower() in parameters:
            raise ValueError("invalid or repeated Content-Type parameter")
        parameters[key.lower()] = item
    return name, parameters


def matches_media(declared: str, actual: str) -> bool:
    expected, constraints = media_type(declared)
    found, parameters = media_type(actual)
    expected_type, expected_subtype = expected.split("/")
    found_type, found_subtype = found.split("/")
    if "*" in found:
        raise ValueError("response Content-Type must be concrete")
    return (
        expected_type in ("*", found_type) and expected_subtype in ("*", found_subtype)
    ) and all(
        parameters.get(key, "").lower() == value.lower()
        if key == "charset"
        else parameters.get(key) == value
        for key, value in constraints.items()
    )


def text_encoding(content_type: str) -> str:
    charset = media_type(content_type)[1].get("charset", "utf-8")
    if charset.lower() not in ("utf-8", "utf8"):
        raise ValueError("only UTF-8 text and JSON response bodies are supported")
    return "utf-8"


def _binary(value: JsonValue) -> bytes:
    if not isinstance(value, str):
        raise ValueError("binary bodies require a generated bytes field")
    return base64.b64decode(value, validate=True)


def _quoted(value: str) -> str:
    if any(ord(char) < 32 or ord(char) == 127 for char in value):
        raise ValueError("invalid multipart field name")
    return value.replace("\\", "\\\\").replace('"', '\\"')


def encode_body(metadata: Body, value: JsonValue) -> tuple[str, bytes]:
    content_type = metadata.content_type
    if content_type is None:
        raise ValueError("body variant must select a content type")
    codec = metadata.codec
    if codec == "binary":
        return content_type, _binary(value)
    if codec == "text":
        if not isinstance(value, str):
            raise ValueError("text bodies require a string")
        return content_type, value.encode(text_encoding(content_type))
    if codec == "ndjson":
        if not isinstance(value, list):
            raise ValueError("NDJSON record bodies require a sequence")
        return content_type, b"".join(
            serialize_json_value(record).encode("utf-8") + b"\n" for record in value
        )
    if codec == "yaml":
        return content_type, serialize_value(
            value, format=SerializationFormat.YAML
        ).encode(text_encoding(content_type))
    if codec == "json":
        text_encoding(content_type)
        return content_type, serialize_json_value(value).encode("utf-8")
    if not isinstance(value, dict):
        raise ValueError("form bodies require an object")
    encodings = {field.name: field for field in metadata.encoding}
    if codec == "urlencoded":
        query: list[tuple[str, str]] = []
        for name, item in value.items():
            field = encodings.get(name, FormField(name))
            encoded = encode_parameter(
                Query(
                    name,
                    style=field.style,
                    explode=field.explode,
                    content_type=field.content_type,
                    allow_reserved=field.allow_reserved,
                ),
                item,
            )
            if isinstance(encoded, str):
                raise TypeError("form query encoder returned a scalar")
            query.extend(encoded)
        return content_type, "&".join(f"{key}={item}" for key, item in query).encode(
            "ascii"
        )
    if codec != "multipart":
        raise ValueError(f"unsupported body codec {codec!r}")
    parts: list[bytes] = []
    for name, item in value.items():
        field = encodings.get(name, FormField(name))
        # Explicit serialization controls supersede contentType. Multipart
        # expansion follows the parameter rules without URI percent encoding.
        expanded: list[tuple[str, JsonValue]]
        if field.parameter_encoding:
            pairs = encode_parameter(
                Query(
                    name,
                    style=field.style,
                    explode=field.explode,
                    # Multipart has no URI percent-encoding. Always quote then
                    # unquote once here, retaining literal input percent signs.
                    allow_reserved=False,
                ),
                item,
            )
            if isinstance(pairs, str):
                raise TypeError("multipart parameter encoder returned a scalar")
            expanded = [(unquote(key), unquote(value)) for key, value in pairs]
        else:
            # OAS multipart arrays use a separate part for each array element.
            items = item if isinstance(item, list) else [item]
            expanded = [(name, part) for part in items]
        for part_name, part in expanded:
            part_type = field.content_type
            if field.binary and part is not None:
                encoded = _binary(part)
                part_type = part_type or "application/octet-stream"
            elif part_type is not None and Body(part_type).codec in ("json", "yaml"):
                # An explicit structured media representation takes precedence
                # over format annotations, including format:binary on strings.
                _, encoded = encode_body(Body(part_type), part)
            elif isinstance(part, (dict, list)) or part is None:
                if part_type is not None:
                    raise ValueError(
                        "structured multipart parts require JSON or YAML media"
                    )
                encoded = serialize_json_value(part).encode("utf-8")
                part_type = "application/json"
            else:
                encoded = scalar(part).encode(text_encoding(part_type or "text/plain"))
                part_type = part_type or "text/plain"
            media_type(part_type)
            disposition = f'Content-Disposition: form-data; name="{_quoted(part_name)}"'
            if field.binary:
                # A filename marks a file part; the schema supplies no filename.
                disposition += f'; filename="{_quoted(part_name)}"'
            parts.append(
                (disposition + "\r\nContent-Type: " + part_type + "\r\n\r\n").encode(
                    "utf-8"
                )
                + encoded
                + b"\r\n"
            )
    while True:
        boundary = "jsoncompat-" + secrets.token_hex(16)
        marker = boundary.encode("ascii")
        if all(marker not in part for part in parts):
            break
    body = b"".join(b"--" + marker + b"\r\n" + part for part in parts)
    body += b"--" + marker + b"--\r\n"
    return content_type + "; boundary=" + boundary, body


def decode_body(codec: BodyCodec, content_type: str, value: bytes) -> JsonValue:
    if codec == "binary":
        return base64.b64encode(value).decode("ascii")
    if codec == "text":
        return value.decode(text_encoding(content_type))
    if codec == "ndjson":
        text_encoding(content_type)
        # Empty records are forbidden by NDJSON; permit the final newline only.
        lines = value.split(b"\n")
        if lines[-1] == b"":
            lines.pop()
        lines = [line.removesuffix(b"\r") for line in lines]
        if any(not line.strip() for line in lines):
            raise ValueError("NDJSON contains an empty record")
        return [deserialize_json_value(line) for line in lines]
    if codec == "yaml":
        try:
            return deserialize_value(
                value.decode(text_encoding(content_type)),
                format=SerializationFormat.YAML,
            )
        except ImportError:
            raise
        except Exception as error:
            # PyYAML's syntax exceptions are not ValueError subclasses. Normalize
            # codec failures so declared errors retain UnexpectedResponse behavior.
            if type(error).__module__.startswith("yaml"):
                raise ValueError(f"invalid YAML response: {error}") from error
            raise
    if codec == "json":
        text_encoding(content_type)
        return deserialize_json_value(value)
    raise ValueError(f"unsupported response body codec {codec!r}")
